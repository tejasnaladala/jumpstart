// FounderGraphHero — the big version. Replaces the 9-node star pattern
// with a 30-node clustered network: AI-infra, biotech, devtools,
// climate/hardtech, agents, fintech, ml-research, policy. Many
// people-to-people edges (not just YOU-to-others) so the graph reads
// as cohort fabric.
//
// One narrative path is highlighted with animated dash-draw:
// YOU → bridge node (AI-agents friend) → bridge node (cross-cluster
// peer) → TARGET (Maya Chen, ML researcher with voice-agents focus).
// A quote bubble floats over the highlighted path: "i want someone
// who can ship the routing layer for voice agents." A small profile
// chip floats next to the target showing why she's the answer.
//
// Visual register: big SVG (viewBox 1600x900), responsive via
// width="100%" h-auto. No three.js — pure SVG so it stays selectable,
// screen-readable, and ~3KB (vs the framer-canvas equivalent). All
// motion is CSS keyframes (stroke-dasharray for the path draw, slow
// pulse for the YOU node, holo shimmer for the target).
//
// Accessibility: role="img", aria-label describes the graph. The
// quote text is rendered as real DOM (foreignObject) so it's
// selectable and screen-reader-friendly.

